use serde::{Deserialize, Serialize};

pub const APP_NAME: &str = "WSID";
pub const APP_FULL_NAME: &str = "What Should I Do? (WSID)";
pub const APP_VERSION: &str = env!("CARGO_PKG_VERSION");
pub const APP_LICENSE_SPDX: &str = "Apache-2.0";
pub const APP_REPOSITORY_URL: &str = "https://github.com/WhatShouldIDoToday/WSID";
pub const APP_LICENSE_TEXT: &str = include_str!("../../../LICENSE");
pub const THIRD_PARTY_NOTICES_TEXT: &str = include_str!("licenses/THIRD_PARTY_NOTICES.txt");
pub const RUST_LICENSES_JSON: &str = include_str!("licenses/rust_licenses.json");

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LicenseOverviewCount {
    pub id: String,
    pub name: String,
    pub count: usize,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CrateAttribution {
    pub name: String,
    pub version: String,
    pub authors: Vec<String>,
    pub repository: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LicenseGroup {
    pub id: String,
    pub name: String,
    pub text: String,
    pub used_by: Vec<CrateAttribution>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct RustLicenseBundle {
    pub overview: Vec<LicenseOverviewCount>,
    pub licenses: Vec<LicenseGroup>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AboutMetadata {
    pub app_name: String,
    pub app_full_name: String,
    pub version: String,
    pub license_spdx: String,
    pub repository_url: String,
    pub license_text: String,
    pub rust_licenses: RustLicenseBundle,
}

/// Parses and returns the embedded Rust third-party license bundle generated by `cargo-about`,
/// consolidating groups by SPDX license ID and deduplicating crate attributions.
pub fn load_rust_license_bundle() -> RustLicenseBundle {
    let raw: RustLicenseBundle =
        serde_json::from_str(RUST_LICENSES_JSON).unwrap_or(RustLicenseBundle { overview: Vec::new(), licenses: Vec::new() });

    let mut merged_groups: Vec<LicenseGroup> = Vec::new();
    for group in raw.licenses {
        if let Some(existing) = merged_groups.iter_mut().find(|g| g.id == group.id) {
            for krate in group.used_by {
                let already_present = existing
                    .used_by
                    .iter()
                    .any(|c| c.name == krate.name && c.version == krate.version);
                if !already_present {
                    existing.used_by.push(krate);
                }
            }
            if existing.text.trim().is_empty() && !group.text.trim().is_empty() {
                existing.text = group.text;
            }
        } else {
            let mut deduped_used_by: Vec<CrateAttribution> = Vec::new();
            for krate in group.used_by {
                if !deduped_used_by
                    .iter()
                    .any(|c| c.name == krate.name && c.version == krate.version)
                {
                    deduped_used_by.push(krate);
                }
            }
            merged_groups.push(LicenseGroup { id: group.id, name: group.name, text: group.text, used_by: deduped_used_by });
        }
    }

    for group in &mut merged_groups {
        group
            .used_by
            .sort_by(|a, b| a.name.cmp(&b.name).then_with(|| a.version.cmp(&b.version)));
    }
    merged_groups.sort_by(|a, b| {
        b.used_by
            .len()
            .cmp(&a.used_by.len())
            .then_with(|| a.id.cmp(&b.id))
    });

    let overview = merged_groups
        .iter()
        .map(|g| LicenseOverviewCount { id: g.id.clone(), name: g.name.clone(), count: g.used_by.len() })
        .collect();

    RustLicenseBundle { overview, licenses: merged_groups }
}

/// Returns complete application metadata, project Apache-2.0 license text, and structured Rust third-party notices.
pub fn get_about_metadata() -> AboutMetadata {
    AboutMetadata {
        app_name: APP_NAME.to_string(),
        app_full_name: APP_FULL_NAME.to_string(),
        version: APP_VERSION.to_string(),
        license_spdx: APP_LICENSE_SPDX.to_string(),
        repository_url: APP_REPOSITORY_URL.to_string(),
        license_text: APP_LICENSE_TEXT.to_string(),
        rust_licenses: load_rust_license_bundle(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn loads_embedded_about_metadata_and_third_party_rust_licenses() {
        let meta = get_about_metadata();
        assert_eq!(meta.app_name, "WSID");
        assert_eq!(meta.license_spdx, "Apache-2.0");
        assert_eq!(meta.repository_url, "https://github.com/WhatShouldIDoToday/WSID");
        assert!(meta.license_text.contains("Apache License"));
        assert!(!meta.rust_licenses.overview.is_empty());
        assert!(!meta.rust_licenses.licenses.is_empty());
        assert_eq!(meta.rust_licenses.overview.len(), meta.rust_licenses.licenses.len());
        let mut seen_ids = std::collections::HashSet::new();
        for group in &meta.rust_licenses.licenses {
            assert!(seen_ids.insert(group.id.clone()), "duplicate license group id: {}", group.id);
            let mut seen_crates = std::collections::HashSet::new();
            for krate in &group.used_by {
                assert!(
                    seen_crates.insert((krate.name.clone(), krate.version.clone())),
                    "duplicate crate attribution {} {} in license {}",
                    krate.name,
                    krate.version,
                    group.id
                );
            }
        }
        assert!(THIRD_PARTY_NOTICES_TEXT.contains("Third-Party Open-Source Licenses"));
    }
}
