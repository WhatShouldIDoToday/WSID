use serde::{Deserialize, Serialize};

pub const APP_NAME: &str = "WSID";
pub const APP_FULL_NAME: &str = "What Should I Do? (WSID)";
pub const APP_VERSION: &str = env!("CARGO_PKG_VERSION");
pub const APP_LICENSE_SPDX: &str = "Apache-2.0";
pub const APP_REPOSITORY_URL: &str = "https://github.com/dmbeta/WSID";
pub const APP_LICENSE_TEXT: &str = include_str!("../../../LICENSE");
pub const THIRD_PARTY_NOTICES_TEXT: &str = include_str!("licenses/THIRD_PARTY_NOTICES.txt");
pub const RUST_LICENSES_JSON: &str = include_str!("licenses/rust_licenses.json");

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LicenseOverviewCount {
    pub id: String,
    pub name: String,
    pub count: usize,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CrateAttribution {
    pub name: String,
    pub version: String,
    pub authors: Vec<String>,
    pub repository: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LicenseGroup {
    pub id: String,
    pub name: String,
    pub text: String,
    pub used_by: Vec<CrateAttribution>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct RustLicenseBundle {
    pub overview: Vec<LicenseOverviewCount>,
    pub licenses: Vec<LicenseGroup>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AboutMetadata {
    pub app_name: String,
    pub app_full_name: String,
    pub version: String,
    pub license_spdx: String,
    pub repository_url: String,
    pub license_text: String,
    pub rust_licenses: RustLicenseBundle,
}

/// Parses and returns the embedded Rust third-party license bundle generated by `cargo-about`.
pub fn load_rust_license_bundle() -> RustLicenseBundle {
    serde_json::from_str(RUST_LICENSES_JSON).unwrap_or(RustLicenseBundle { overview: Vec::new(), licenses: Vec::new() })
}

/// Returns complete application metadata, project Apache-2.0 license text, and structured Rust third-party notices.
pub fn get_about_metadata() -> AboutMetadata {
    AboutMetadata {
        app_name: APP_NAME.to_string(),
        app_full_name: APP_FULL_NAME.to_string(),
        version: APP_VERSION.to_string(),
        license_spdx: APP_LICENSE_SPDX.to_string(),
        repository_url: APP_REPOSITORY_URL.to_string(),
        license_text: APP_LICENSE_TEXT.to_string(),
        rust_licenses: load_rust_license_bundle(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn loads_embedded_about_metadata_and_third_party_rust_licenses() {
        let meta = get_about_metadata();
        assert_eq!(meta.app_name, "WSID");
        assert_eq!(meta.license_spdx, "Apache-2.0");
        assert_eq!(meta.repository_url, "https://github.com/dmbeta/WSID");
        assert!(meta.license_text.contains("Apache License"));
        assert!(!meta.rust_licenses.overview.is_empty());
        assert!(!meta.rust_licenses.licenses.is_empty());
        assert!(THIRD_PARTY_NOTICES_TEXT.contains("Third-Party Open-Source Licenses"));
    }
}
